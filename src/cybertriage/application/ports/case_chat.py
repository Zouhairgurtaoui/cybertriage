"""Conversation persistence and background processing boundaries."""

from collections.abc import Mapping
from typing import Any, Protocol

from cybertriage.domain.case_chat import ChatClaim, ChatReply


class CaseConversationStore(Protocol):
    def submit(self, case_id: str, content: str, actor: str, expected_version: int,
               idempotency_key: str, mode: str, anchor_alert_id: str | None) -> Mapping[str, object]: ...
    def list_turns(self, case_id: str, limit: int = 20, before: int | None = None) -> Mapping[str, object]: ...
    def turn_detail(self, case_id: str, turn_id: str) -> Mapping[str, object]: ...


class ChatQueue(Protocol):
    def claim(self, lease_seconds: int = 600) -> ChatClaim | None: ...
    def context(self, claim: ChatClaim) -> Mapping[str, Any]: ...
    def renew(self, claim: ChatClaim, lease_seconds: int = 600) -> None: ...
    def complete(self, claim: ChatClaim, reply: ChatReply) -> None: ...
    def fail(self, claim: ChatClaim, code: str, retryable: bool) -> None: ...


class ChatTurnProcessor(Protocol):
    def execute(self, claim: ChatClaim) -> ChatReply: ...
