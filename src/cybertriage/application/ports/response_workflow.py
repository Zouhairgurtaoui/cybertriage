from collections.abc import Mapping, Sequence
from typing import Protocol

from cybertriage.domain.response import ActionProposal
from cybertriage.domain.response_workflow import ExecutionOutcome, ExecutionRequest, ResponsePolicySnapshot


class ResponseRepository(Protocol):
    def propose(self, proposal: ActionProposal, supporting_ids: Sequence[str], expected_version: int,
                actor: str, reason: str, origin: str, idempotency_key: str, analysis_id: str | None,
                snapshot: ResponsePolicySnapshot) -> Mapping[str, object]: ...
    def review(self, proposal_id: str, decision: str, expected_version: int, actor: str, reason: str,
               snapshot: ResponsePolicySnapshot) -> Mapping[str, object]: ...
    def get(self, proposal_id: str) -> Mapping[str, object]: ...
    def list(self, case_id: str, limit: int, after: int) -> Mapping[str, object]: ...
    def claim(self, proposal_id: str, expected_version: int, actor: str, reason: str,
              snapshot: ResponsePolicySnapshot) -> ExecutionRequest: ...
    def finish(self, request: ExecutionRequest, outcome: ExecutionOutcome) -> Mapping[str, object]: ...
    def reconcile(self, execution_id: str, outcome: str, actor: str, reason: str, evidence: str) -> Mapping[str, object]: ...
    def reconcile_block_release(self, execution_id: str, actor: str, reason: str, evidence: str) -> Mapping[str, object]: ...


class BlockLeaseRepository(Protocol):
    def claim_expired_block(self, target_revision: str) -> Mapping[str, object] | None: ...
    def finish_block_release(self, lease: Mapping[str, object], released: bool) -> Mapping[str, object]: ...


class ActionExecutor(Protocol):
    def execute(self, request: ExecutionRequest) -> ExecutionOutcome: ...
